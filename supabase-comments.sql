create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  item_type text not null check (item_type in ('film', 'series', 'anime')),
  item_id text not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  author_name text not null check (char_length(btrim(author_name)) between 2 and 32),
  body text not null check (char_length(btrim(body)) between 3 and 1200),
  created_at timestamptz not null default now()
);

create index if not exists comments_item_created_idx
  on public.comments (item_type, item_id, created_at desc);

alter table public.comments enable row level security;
revoke all on table public.comments from anon, authenticated;
grant select, insert on table public.comments to authenticated;
grant usage, select on sequence public.comments_id_seq to authenticated;

drop policy if exists "Signed-in users can read comments" on public.comments;
create policy "Signed-in users can read comments"
  on public.comments for select
  to authenticated
  using (true);

drop policy if exists "Users can add comments as themselves" on public.comments;
create policy "Users can add comments as themselves"
  on public.comments for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and author_name = coalesce((select auth.jwt() -> 'user_metadata' ->> 'display_name'), '')
  );
